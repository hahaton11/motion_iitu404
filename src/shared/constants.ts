/**
 * Скорость отпускания, выше которой release превращается в throw. Доли экрана в секунду.
 *
 * Снято с записи живого движения (`test-assets/fixtures/throw-*.json`, `scripts/diagnose-throw.ts`) —
 * с того самого сигнала, который видит машина состояний: после One Euro и в координатах экрана.
 *
 *   медиана 0.44   p90 1.36   p99 3.35   max 5.16
 *
 * Значение какое-то время стояло 1.2. Оно было снято с датасета, по сырым точкам ладони и без
 * фильтра, и дало заниженные скорости — максимум 1.77 вместо настоящих 5.16. Вывод «порог выше
 * физического максимума руки» был следствием того, что мерили не тот сигнал. На 1.2 броском
 * становилось каждое девятое движение, и смоук это поймал: плавный перенос в обучении удалял
 * элемент вместо того, чтобы положить его в рамку.
 *
 * 2.2 лежит между p90 и p99: спокойный перенос впятеро не долетает, намеренный мах проходит
 * с запасом. Мерить такие пороги можно только на записи самого движения — на протоколе поз,
 * где каждый жест показывают почти неподвижно, броска нет вовсе.
 */
export const THROW_SPEED = 2.2

/**
 * Сколько живёт запомненный мах. Поза отпускания приходит от классификатора с задержкой: голосователю
 * нужно 4 уверенных кадра из 6, и на 15 кадрах в секунду это до 400 мс после конца маха, когда рука
 * уже стоит. Мгновенная скорость в этот момент нулевая, поэтому бросок решается по самой быстрой
 * скорости за это окно, а не по скорости в кадре раскрытия.
 *
 * Окно должно быть длиннее задержки голосователя и длиннее HAND_LOST_MS, иначе мах успевает забыться.
 * Длиннее делать нельзя: перенёс быстро, постоял, спокойно отпустил — это отпускание, а не бросок.
 * Совпадает с SWIPE_MAX_MS: там та же граница между махом и переносом руки.
 */
export const THROW_MEMORY_MS = 450

/** Удержание указательного жеста до события point. */
export const POINT_HOLD_MS = 600

/** Окно, по которому считается скорость руки или мыши. */
export const VELOCITY_WINDOW_MS = 80

/**
 * Эмуляция зума щипком мышью: Alt и перетаскивание вверх или вниз. factor = exp(-dy * gain),
 * dy в долях экрана. Совпадает с усилением зума щипком у камеры: мышь учит тому же движению.
 */
export const MOUSE_PINCH_ZOOM_GAIN = 2.5
